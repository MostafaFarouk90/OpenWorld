// Picks Cinderreach's sub-sites on the real ground and writes src/cinderreach/sitesFit.ts:
//   npx vite-node tools/fit-cinderreach-sites.ts
// Deterministic. Run it again (and commit the file) when A1 moves a plateau or road.
import { writeFileSync } from 'node:fs';
import { findDips, findFlat, findScatterCentre, type Avoid, type Pt } from '../src/cinderreach/siteFit';
import { M11_STONE, PASTURE_FOLD, PASTURE, SCORCHHOLD, STONEFOLD } from '../src/cinderreach/sites';
import { heightAt } from '../src/terrain/heightfield';

const r = (n: number): number => Math.round(n);
const fail = (msg: string): never => {
  throw new Error(`fit-cinderreach-sites: ${msg}`);
};

// The hunters' camp: the flattest scatter within 150 m of the fort's south-east shoulder, then each prop on its own flat spot.
const prefer: Pt = { x: SCORCHHOLD.x + 400, z: SCORCHHOLD.z - 150 };
const camp = findScatterCentre(heightAt, prefer, 150, 40, 5, 0.4, 15);
type Item = { x: number; z: number; yaw: number };
const placed: Avoid[] = [];
const place = (size: [number, number], at: Pt, label: string, radius = 30): Item => {
  const hit = findFlat(heightAt, { prefer: at, radius, size, maxSpread: 0.45, avoid: placed, step: 3 }) ?? fail(`no flat spot for ${label}`);
  placed.push({ ...hit, r: Math.max(...size) / 2 + 1 });
  return { x: r(hit.x), z: r(hit.z), yaw: 0 };
};
const at = (deg: number, dist: number): Pt => ({ x: camp.x + dist * Math.sin((deg * Math.PI) / 180), z: camp.z + dist * Math.cos((deg * Math.PI) / 180) });
const tents = [0, 90, 180, 270].map((d, i) => place([5, 5], at(d, 24), `tent ${i + 1}`));
const cages = [45, 165, 285].map((d, i) => place([3, 3], at(d, 13), `cage ${i + 1}`));
const desks = [20, 200].map((d, i) => place([2.2, 1.2], at(d, 6), `desk ${i + 1}`));
const crates = [100, 220, 340].map((d, i) => place([1.4, 1.4], at(d, 18), `crate ${i + 1}`));

// The M11 stone beside the road (the stone's anchor stands 1.8 m south of it) and the blightbloom ring round it.
const stone = place([1.6, 1.6], { x: M11_STONE.x, z: M11_STONE.z + 1.8 }, 'the M11 stone', 15);
const blooms = [30, 150, 270].map((d, i) => place([3, 3], { x: stone.x + 10 * Math.sin((d * Math.PI) / 180), z: stone.z + 10 * Math.cos((d * Math.PI) / 180) }, `bloom ${i + 1}`, 14));

// Ketta's sheepfold: a 10 m yard on the nearest flat ground to the track's end.
const fold = place([10, 10], PASTURE_FOLD, 'the sheepfold', 150);

// The hound den: a 30 m flat spot at the north-east of Stonefold's plateau, outside the holdfast wall.
const holdfast: Avoid = { x: STONEFOLD.x, z: STONEFOLD.z, r: 90 };
const hound = findFlat(heightAt, { prefer: { x: STONEFOLD.x + 140, z: STONEFOLD.z + 140 }, radius: 140, size: [30, 30], maxSpread: 0.45, avoid: [holdfast], within: STONEFOLD.box, step: 5 }) ?? fail('no flat spot for the hound den');

// The pasture: the five deepest dips, 80 m apart; the deepest is the Kindling Dell, the next three are the fog hollows.
const dips = findDips(heightAt, { box: PASTURE.box, count: 4, minSeparation: 80, radius: 30, step: 10 });
if (dips.length < 4) fail(`only ${dips.length} dips in the pasture`);

const pt = (p: Pt): string => `{ x: ${r(p.x)}, z: ${r(p.z)} }`;
const items = (xs: Item[]): string => `[${xs.map((i) => `{ x: ${i.x}, z: ${i.z}, yaw: ${i.yaw} }`).join(', ')}]`;
const out = `// GENERATED by tools/fit-cinderreach-sites.ts on the real heightAt. Do not edit; rerun the tool when A1 moves a plateau.
// sitesFit.test.ts re-checks every number here against the ground.
export const SITES_FIT = {
  camp: {
    centre: ${pt(camp)},
    tents: ${items(tents)},
    cages: ${items(cages)},
    desks: ${items(desks)},
    crates: ${items(crates)},
  },
  stone: ${items([stone]).slice(1, -1)},
  blooms: ${items(blooms)},
  fold: ${items([fold]).slice(1, -1)},
  houndDen: ${pt(hound)},
  dell: ${pt(dips[0])},
  hollows: [${dips.slice(1, 4).map(pt).join(', ')}],
} as const;
`;
writeFileSync(new URL('../src/cinderreach/sitesFit.ts', import.meta.url), out);
console.log(out);
