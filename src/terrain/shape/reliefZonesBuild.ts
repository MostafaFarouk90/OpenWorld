// Builds the keep-flat table for the Brightwater detail relief (`detailRelief.ts`) from the layout data.
// Used by tools/env-pass/gen-relief-zones.ts to write `detailReliefZones.ts`, and by a test that fails when that file drifts.
import type { LayoutData } from '../../region/layoutTypes';
import { footprintCorners } from '../../region/geometry';

/** Cell edge in metres: every cell holding a layout item, plus one ring around it, stays flat. */
export const ZONE_CELL = 10;
/** Region the table covers: the B1 tile core plus its blend band (`detailRelief.ts` returns 0 outside). */
export const ZONE_BOUNDS = { x0: -160, x1: 220, z0: -90, z1: 290 } as const;

/** Box triggers with a horizontal half extent from this size on (region strips) are ignored. */
const MAX_TRIGGER_HALF = 40;

/** Axis-aligned flat rectangle [x0, z0, x1, z1] in metres. */
export type ZoneRect = readonly [number, number, number, number];

/** Occupied cells (anchors, sphere and box trigger centres and corners, structure footprint corners and centres) dilated by one ring, merged into rectangles. */
export function buildReliefZones(layout: Pick<LayoutData, 'anchors' | 'triggers' | 'structures'>): ZoneRect[] {
  const cols = Math.ceil((ZONE_BOUNDS.x1 - ZONE_BOUNDS.x0) / ZONE_CELL);
  const rows = Math.ceil((ZONE_BOUNDS.z1 - ZONE_BOUNDS.z0) / ZONE_CELL);
  const occ = new Uint8Array(cols * rows);
  const mark = (x: number, z: number): void => {
    const i = Math.floor((x - ZONE_BOUNDS.x0) / ZONE_CELL);
    const j = Math.floor((z - ZONE_BOUNDS.z0) / ZONE_CELL);
    if (i < 0 || j < 0 || i >= cols || j >= rows) return;
    for (let dj = -1; dj <= 1; dj++) {
      for (let di = -1; di <= 1; di++) {
        const ii = i + di;
        const jj = j + dj;
        if (ii >= 0 && jj >= 0 && ii < cols && jj < rows) occ[jj * cols + ii] = 1;
      }
    }
  };
  // Marks the cells under a rectangle, not just its corners, so large footprints and triggers fill solid.
  const markRect = (x0: number, z0: number, x1: number, z1: number): void => {
    for (let x = x0; x <= x1 + ZONE_CELL; x += ZONE_CELL) for (let z = z0; z <= z1 + ZONE_CELL; z += ZONE_CELL) mark(Math.min(x, x1), Math.min(z, z1));
  };
  for (const a of layout.anchors) mark(a.x, a.z);
  for (const t of layout.triggers) {
    // Region and road trigger strips are far larger than any dressing; they are not ground the player stands on precisely.
    if (t.shape === 'box' && Math.max(t.half[0], t.half[2]) >= MAX_TRIGGER_HALF) continue;
    const r = t.shape === 'sphere' ? t.radius : Math.hypot(t.half[0], t.half[2]);
    markRect(t.x - r, t.z - r, t.x + r, t.z + r);
  }
  for (const s of layout.structures) {
    const c = footprintCorners(s);
    const xs = c.map((p) => p[0]);
    const zs = c.map((p) => p[1]);
    markRect(Math.min(...xs), Math.min(...zs), Math.max(...xs), Math.max(...zs));
  }
  // Horizontal runs per row, then merge identical runs on consecutive rows.
  type Run = { i0: number; i1: number; j0: number; j1: number };
  const done: Run[] = [];
  let open: Run[] = [];
  for (let j = 0; j <= rows; j++) {
    const runs: Array<[number, number]> = [];
    if (j < rows) {
      let i = 0;
      while (i < cols) {
        if (!occ[j * cols + i]) {
          i++;
          continue;
        }
        const i0 = i;
        while (i < cols && occ[j * cols + i]) i++;
        runs.push([i0, i - 1]);
      }
    }
    const next: Run[] = [];
    for (const [i0, i1] of runs) {
      const k = open.findIndex((r) => r.i0 === i0 && r.i1 === i1);
      if (k >= 0) {
        next.push({ ...open[k]!, j1: j });
        open.splice(k, 1);
      } else next.push({ i0, i1, j0: j, j1: j });
    }
    done.push(...open);
    open = next;
  }
  return done
    .map((r): ZoneRect => [ZONE_BOUNDS.x0 + r.i0 * ZONE_CELL, ZONE_BOUNDS.z0 + r.j0 * ZONE_CELL, ZONE_BOUNDS.x0 + (r.i1 + 1) * ZONE_CELL, ZONE_BOUNDS.z0 + (r.j1 + 1) * ZONE_CELL])
    .sort((p, q) => p[0] - q[0] || p[1] - q[1]);
}

/** Source text of `detailReliefZones.ts`. */
export function renderReliefZones(zones: readonly ZoneRect[]): string {
  const rows = zones.map((z) => `  [${z.join(', ')}],`).join('\n');
  return `// Generated by tools/env-pass/gen-relief-zones.ts from the Brightwater layout; a test fails when this file drifts.
// Keep-flat rectangles [x0, z0, x1, z1] in metres: \`detailRelief\` is zero inside them and ramps in over RELIEF_BLEND outside.
import type { ZoneRect } from './reliefZonesBuild';

export const RELIEF_ZONES: readonly ZoneRect[] = [
${rows}
];
`;
}
